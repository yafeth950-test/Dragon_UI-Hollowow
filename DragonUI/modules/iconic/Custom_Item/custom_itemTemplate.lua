local function OnTooltipSetItem(tooltip, ...)
    if addon.IsModuleEnabled and not addon:IsModuleEnabled("iconic") then
        return
    end
    local itemName, itemLink = tooltip:GetItem()
    if itemLink then
        local itemID = tonumber(itemLink:match("item:(%d+):"))
        local itemNameLine = _G[tooltip:GetName() .. "TextLeft1"]
        
        if itemID and itemNameLine then
            local itemNameText = itemNameLine:GetText()
            local descriptionKey = itemDescriptions[itemID]
            local description = descriptions[descriptionKey]
            
            if description then
                -- Полная локаль GetLocale() (deDE, frFR, …), иначе наследуемые ключи en / ru
                local loc = GetLocale()
                local localizedDescription = description[loc]
                    or (loc == "ruRU" and description.ru)
                    or description.en
                    or description.ru
                itemNameLine:SetText(itemNameText .. "\n" .. localizedDescription .. "|r")
            end

            tooltip:Show()
        end
    end
end

local tooltips = {
    GameTooltip,
    ItemRefTooltip,
    ItemRefShoppingTooltip1,
    ItemRefShoppingTooltip2,
    ItemRefShoppingTooltip3,
    ShoppingTooltip1,
    ShoppingTooltip2,
    ShoppingTooltip3,
}

for _, tt in ipairs(tooltips) do
    if tt and tt.HookScript then
        tt:HookScript("OnTooltipSetItem", OnTooltipSetItem)
    end
end
